    #[test]
    fn nft_lockdown_ruleset_blocks_by_default_with_loopback_and_dhcp_only() {
        let s = lockdown_nft_ruleset();
        assert!(s.contains("policy drop;"), "must fail closed:\n{s}");
        assert!(s.contains("oifname \"lo\" accept"), "loopback stays usable");
        assert!(s.contains("udp dport {67, 68} accept"), "DHCP renewal");
        assert!(
            !s.contains("meta l4proto udp accept") && !s.contains("daddr"),
            "no exit or destination exception may exist in a lockdown block:\n{s}"
        );
    }

    #[test]
    fn nft_lockdown_ruleset_uses_the_atomic_replace_pattern_on_warrends_own_table() {
        let s = lockdown_nft_ruleset();
        let add = s.find("add table inet warrend_lockdown").expect("add");
        let flush = s.find("flush table inet warrend_lockdown").expect("flush");
        let body = s.find("table inet warrend_lockdown {").expect("body");
        assert!(add < flush && flush < body, "atomic replace order:\n{s}");
        assert!(
            !s.contains(ENGINE_NFT_TABLE),
            "the lockdown block must NOT live in the engine table: the engine \
             teardown flushes that one and would open the network:\n{s}"
        );
    }

