    // ---- DNS reconcile (Linux file logic, any host) ------------------

    fn tempdir() -> std::path::PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "warrend-dns-test-{}-{:?}",
            std::process::id(),
            std::thread::current().id()
        ));
        std::fs::create_dir_all(&dir).expect("tempdir");
        dir
    }

    #[test]
    fn dns_restore_puts_the_backup_back_when_resolv_conf_is_still_ours() {
        let dir = tempdir();
        let resolv = dir.join("resolv.conf");
        let backup = dir.join("resolv.conf.bak");
        std::fs::write(
            &resolv,
            warrenguard_route_split::dns_push::build_resolv_conf(&[
                warrenguard_config::TUNNEL_GATEWAY_IP,
            ]),
        )
        .expect("write override");
        std::fs::write(&backup, "nameserver 192.168.1.1\n").expect("write backup");

        let outcome = reconcile_dns_files(&resolv, &backup).expect("reconcile");
        assert_eq!(outcome, DnsReconcile::RestoredBackup);
        assert_eq!(
            std::fs::read_to_string(&resolv).expect("read"),
            "nameserver 192.168.1.1\n",
            "the pre-tunnel config must be back in place"
        );
        assert!(!backup.exists(), "the backup was consumed by the restore");
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn dns_restore_drops_a_stale_backup_when_resolv_conf_was_rewritten_by_others() {
        let dir = tempdir();
        let resolv = dir.join("resolv.conf");
        let backup = dir.join("resolv.conf.bak");
        std::fs::write(&resolv, "# NetworkManager\nnameserver 1.1.1.1\n").expect("write foreign");
        std::fs::write(&backup, "nameserver 192.168.1.1\n").expect("write backup");

        let outcome = reconcile_dns_files(&resolv, &backup).expect("reconcile");
        assert_eq!(outcome, DnsReconcile::RemovedStaleBackup);
        assert_eq!(
            std::fs::read_to_string(&resolv).expect("read"),
            "# NetworkManager\nnameserver 1.1.1.1\n",
            "a foreign resolv.conf is the live truth and must not be clobbered"
        );
        assert!(
            !backup.exists(),
            "the stale backup must go away so the next engine install is not refused"
        );
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn dns_restore_is_a_noop_when_no_backup_exists() {
        let dir = tempdir();
        let resolv = dir.join("resolv.conf");
        std::fs::write(&resolv, "nameserver 9.9.9.9\n").expect("write");
        let outcome =
            reconcile_dns_files(&resolv, &dir.join("resolv.conf.bak")).expect("reconcile");
        assert_eq!(outcome, DnsReconcile::Clean);
        std::fs::remove_dir_all(&dir).ok();
    }

