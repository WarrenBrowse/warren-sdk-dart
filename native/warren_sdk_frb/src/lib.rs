//! flutter_rust_bridge glue for the Warren engine (Mode A, in-process).
//!
//! This crate is a thin delegation layer: every function forwards to the audited
//! `warren-sdk` engine. No protocol logic lives here. flutter_rust_bridge scans
//! the `api` module and generates the Dart bindings consumed by
//! `warren_sdk_ffi`.
//!
//! No-log discipline: errors crossing the bridge are redacted and never carry a
//! pubkey, address, IP, nonce or seed in clear.

pub mod api;

// In-tunnel egress liveness probe (doc 62 item 5): client-side health
// logic over the session's own SOCKS5 endpoint, not protocol code. Not
// under `api` on purpose: nothing here is bridged directly.

// Generated by `flutter_rust_bridge_codegen`; regenerate with `melos run gen`.
// Checked in so the crate builds without the codegen toolchain present.
#[cfg(not(frb_expand))]
mod frb_generated;

// During the codegen expand pass the real generated module is excluded, so the
// concrete `StreamSink` it defines is missing. Provide just that type (via the
// same flutter_rust_bridge macro) so the streaming API still type-checks while
// cargo-expand runs. Never compiled into a normal build.
#[cfg(frb_expand)]
mod frb_generated {
    flutter_rust_bridge::frb_generated_stream_sink!(default_stream_sink_codec = DcoCodec);
}
